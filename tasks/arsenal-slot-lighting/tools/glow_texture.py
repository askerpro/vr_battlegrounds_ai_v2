"""Текстура ленты слота арсенала: свечение только у левого и правого края доски (RGB белый, альфа — спад).

Запуск: python -I tasks/arsenal-slot-lighting/tools/glow_texture.py <выходной .png>
Решение пользователя 2026-10-23: скрытая LED-лента по бокам слота; саму ленту прячет бортик (2 см по краю
доски, половина над доской), из-за него на доску выходит тонкая тёплая полоска ~1,5 см — габарит слота и
индикатор доступности. Расстояния в метрах для доски стены шириной 0,45 м (на полке 0,43 — почти то же).
Квад во всю доску; по высоте альфа постоянна, поэтому текстура — узкая полоса.
"""
import sys

from PIL import Image

W, H = 512, 4
BOARD = 0.45     # ширина доски, м
HIDDEN = 0.01    # от края до внутренней кромки бортика, м: здесь альфа 1 (под бортиком)
GLOW = 0.015     # ширина видимого спада за кромкой, м


def alpha(u):
    d = min(u, 1.0 - u) * BOARD
    t = min(1.0, max(0.0, (d - HIDDEN) / GLOW))
    return (1.0 - t) ** 2


def main(path):
    img = Image.new("RGBA", (W, H))
    px = img.load()
    for x in range(W):
        a = round(255 * alpha((x + 0.5) / W))
        for y in range(H):
            px[x, y] = (255, 255, 255, a)
    img.save(path)


if __name__ == "__main__":
    main(sys.argv[1])
